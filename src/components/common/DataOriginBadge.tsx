import React from 'react';
import styles from './DataOriginBadge.module.css';

interface DataOriginBadgeProps {
  isSimulated?: boolean;
  label?: string;
  className?: string;
  size?: 'sm' | 'md';
}

export const DataOriginBadge: React.FC<DataOriginBadgeProps> = ({
  isSimulated = true,
  label,
  className = '',
  size = 'md',
}) => {
  if (isSimulated) {
    return (
      <span
        className={`${styles.badge} ${styles.simulated} ${size === 'sm' ? styles.small : ''} ${className}`}
        title="This telemetry/data is generated by the demonstration simulation engine"
      >
        <span className={styles.dot}></span>
        {label || 'SIMULATED DEMO DATA'}
      </span>
    );
  }

  return (
    <span
      className={`${styles.badge} ${styles.live} ${size === 'sm' ? styles.small : ''} ${className}`}
      title="Live telemetry received from physical hardware sensor / gateway"
    >
      <span className={styles.dot}></span>
      {label || 'LIVE HARDWARE DATA'}
    </span>
  );
};
